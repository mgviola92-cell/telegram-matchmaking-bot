_recent_notice = defaultdict(lambda: deque(maxlen=4))

def say_notice(event, user_id=None):
    variants = NOTICES[event]
    key = (event, user_id)
    last = _recent_notice[key]
    available = [line for line in variants if line not in last]
    result = random.choice(available or variants)
    last.append(result)
    return result
